import argparse
import json
import math
import re
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

import torch
from peft import PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer


MARKER = "Next absolute coordinates:"
DEFAULT_SCALE_CONFIG = "../BaseLine/absolute_scaling_config.json"
DEC_DIGITS = 5
DEC_SCALE = 10**DEC_DIGITS


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Absolute model inference evaluation on test JSONL.")
    parser.add_argument("--base-model-dir", default="../Meta-Llama-3.1-8B_tokenizerExtension")
    parser.add_argument(
        "--lora-model-dir",
        default="../BaseLine/motionQaAbsoluteFileLevelRobustScaledClipP95Dec5",
    )
    parser.add_argument("--test-jsonl", default="../BaseLine/finetune_dataset_absolute_test.jsonl")
    parser.add_argument("--max-new-tokens", type=int, default=4096)
    parser.add_argument("--min-new-tokens", type=int, default=1024)
    parser.add_argument("--max-samples", type=int, default=0, help="0 means evaluate all samples.")
    parser.add_argument("--do-sample", action="store_true", help="Enable sampling generation.")
    parser.add_argument("--temperature", type=float, default=0.2)
    parser.add_argument("--top-p", type=float, default=0.9)
    parser.add_argument("--repetition-penalty", type=float, default=1.0)
    parser.add_argument("--output-report", default="./absolute_eval_report_fileLevelModel.json")
    parser.add_argument(
        "--failure-log-jsonl",
        default="",
        help="Optional JSONL path to store per-sample failure records. Defaults to <output-report>_failures.jsonl",
    )
    parser.add_argument(
        "--absolute-scale-config",
        default=DEFAULT_SCALE_CONFIG,
        help="Path to robust absolute scaling config JSON generated by converter.",
    )
    parser.add_argument(
        "--no-absolute-scaling",
        action="store_true",
        help="Disable inverse scaling before metric computation.",
    )
    parser.add_argument(
        "--append-target-prefix",
        action="store_true",
        help=(
            "Append '\\nNext absolute coordinates:' to each prompt before generation. "
            "Recommended for this dataset format."
        ),
    )
    parser.add_argument(
        "--debug-failures",
        type=int,
        default=3,
        help="Print raw model outputs for first N parse failures.",
    )
    return parser.parse_args()


def decode_token_number(token_str: str) -> float:
    pattern = r"(-?)\[NUM\]\[INT\](\d{3})\[SEP\]\[DEC\](\d{5})\[ENDNUM\]"
    m = re.search(pattern, token_str)
    if not m:
        raise ValueError(f"Invalid token format: {token_str}")
    sign = -1 if m.group(1) == "-" else 1
    int_part = int(m.group(2))
    dec_part = int(m.group(3))
    return round(sign * (int_part + dec_part / DEC_SCALE), DEC_DIGITS + 1)


def _to_ascii_digits(text: str) -> str:
    out = []
    for ch in text:
        if "0" <= ch <= "9":
            out.append(ch)
            continue
        try:
            out.append(str(unicodedata.digit(ch)))
        except (TypeError, ValueError):
            continue
    return "".join(out)


def _parse_numeric_fragment(fragment: str) -> float | None:
    frag = fragment.strip()
    if not frag:
        return None

    m = re.search(
        r"(-?)\s*\[NUM\]\s*\[INT\]\s*(\d{3})\s*\[SEP\]\s*\[DEC\]\s*(\d{5})\s*\[ENDNUM\]",
        frag,
    )
    if m:
        sign = -1 if m.group(1) == "-" else 1
        int_part = int(m.group(2))
        dec_part = int(m.group(3))
        return round(sign * (int_part + dec_part / DEC_SCALE), DEC_DIGITS + 1)

    sign = -1 if re.search(r"[-−﹣－]", frag) else 1
    digits = _to_ascii_digits(frag)
    if len(digits) >= 8:
        core = digits[-8:]
        int_part = int(core[:3])
        dec_part = int(core[3:8])
        return round(sign * (int_part + dec_part / DEC_SCALE), DEC_DIGITS + 1)

    m = re.search(r"[-+]?\d+(?:\.\d+)?", frag)
    if m:
        try:
            return round(float(m.group(0)), DEC_DIGITS + 1)
        except ValueError:
            return None
    return None


def parse_coords(text: str) -> dict[str, list[tuple[float, float]]]:
    start = text.find(MARKER)
    if start != -1:
        text = text[start + len(MARKER) :]
    text = text.strip()
    if not text:
        return {}

    frame_pat = re.compile(
        r"\(\s*(-?\[NUM\]\[INT\]\d{3}\[SEP\]\[DEC\]\d{5}\[ENDNUM\])\s*"
        r",\s*(-?\[NUM\]\[INT\]\d{3}\[SEP\]\[DEC\]\d{5}\[ENDNUM\])\s*\)"
    )
    joint_pat = re.compile(r"([A-Z][A-Z_]*):")

    result: dict[str, list[tuple[float, float]]] = {}
    matches = list(joint_pat.finditer(text))
    for idx, m in enumerate(matches):
        joint = m.group(1)
        seg_start = m.end()
        seg_end = matches[idx + 1].start() if (idx + 1) < len(matches) else len(text)
        seg = text[seg_start:seg_end]

        frames: list[tuple[float, float]] = []
        for x_tok, y_tok in frame_pat.findall(seg):
            x = decode_token_number(x_tok)
            y = decode_token_number(y_tok)
            frames.append((x, y))

        if not frames:
            for inner in re.findall(r"\(([^()]*)\)", seg):
                parts = re.split(r"[,،|]", inner, maxsplit=1)
                if len(parts) < 2:
                    continue
                x = _parse_numeric_fragment(parts[0])
                y = _parse_numeric_fragment(parts[1])
                if x is None or y is None:
                    continue
                frames.append((x, y))

        if frames:
            result[joint] = frames
    return result


def safe_console_text(text: str) -> str:
    """Convert text to current console encoding safely to avoid print-time crashes."""
    enc = getattr(sys.stdout, "encoding", None) or "utf-8"
    return text.encode(enc, errors="replace").decode(enc, errors="replace")


def classify_format_failure(text: str) -> str:
    t = (text or "").strip()
    if not t:
        return "empty_output"
    if "[NUM]" not in t:
        return "no_num_token"
    if "[SEP][DEC]" not in t and "[SEP]" in t:
        return "missing_dec_after_sep"
    if "[ENDNUM]" not in t:
        return "missing_endnum"
    if "#" in t or "\ufffd" in t:
        return "garbage_symbols"
    return "unparsable_format"


def load_scale_config(scale_config_path: Path):
    if not scale_config_path.exists():
        return {}, 1e-6
    with open(scale_config_path, "r", encoding="utf-8") as f:
        payload = json.load(f)
    eps = float(payload.get("eps", 1e-6))
    scales = payload.get("joint_axis_scale", {})
    normalized = {}
    for joint, axis_scales in scales.items():
        if not isinstance(axis_scales, dict):
            continue
        sx = float(axis_scales.get("x", 1.0))
        sy = float(axis_scales.get("y", 1.0))
        if sx <= 0:
            sx = 1.0
        if sy <= 0:
            sy = 1.0
        normalized[str(joint)] = {"x": sx, "y": sy}
    return normalized, eps


def inverse_scale_coords(
    coords_by_joint: dict[str, list[tuple[float, float]]],
    joint_axis_scales: dict[str, dict[str, float]],
    scale_eps: float,
) -> dict[str, list[tuple[float, float]]]:
    if not joint_axis_scales:
        return coords_by_joint
    restored: dict[str, list[tuple[float, float]]] = {}
    for joint, seq in coords_by_joint.items():
        sx = joint_axis_scales.get(joint, {}).get("x", 1.0)
        sy = joint_axis_scales.get(joint, {}).get("y", 1.0)
        restored[joint] = [(x * (sx + scale_eps), y * (sy + scale_eps)) for x, y in seq]
    return restored


def evaluate_one(
    pred: dict[str, list[tuple[float, float]]],
    gt: dict[str, list[tuple[float, float]]],
) -> dict:
    err_x = []
    err_y = []
    dist = []
    horizon_dist = defaultdict(list)

    common_joints = sorted(set(pred.keys()) & set(gt.keys()))
    aligned_points = 0
    for joint in common_joints:
        n = min(len(pred[joint]), len(gt[joint]))
        for t in range(n):
            x_p, y_p = pred[joint][t]
            x_g, y_g = gt[joint][t]
            ex = abs(x_p - x_g)
            ey = abs(y_p - y_g)
            d = math.sqrt((x_p - x_g) ** 2 + (y_p - y_g) ** 2)
            err_x.append(ex)
            err_y.append(ey)
            dist.append(d)
            horizon_dist[t + 1].append(d)
            aligned_points += 1

    return {
        "common_joints": len(common_joints),
        "aligned_points": aligned_points,
        "mae_x": sum(err_x) / len(err_x) if err_x else None,
        "mae_y": sum(err_y) / len(err_y) if err_y else None,
        "mae_xy": (sum(err_x) + sum(err_y)) / (len(err_x) + len(err_y)) if err_x else None,
        "mean_dist": sum(dist) / len(dist) if dist else None,
        "horizon_dist": {k: (sum(v) / len(v) if v else None) for k, v in horizon_dist.items()},
        "raw_err_x": err_x,
        "raw_err_y": err_y,
        "raw_dist": dist,
        "raw_horizon_dist": horizon_dist,
    }


def main() -> None:
    args = parse_args()
    script_dir = Path(__file__).resolve().parent

    base_model_dir = (script_dir / args.base_model_dir).resolve()
    lora_model_dir = (script_dir / args.lora_model_dir).resolve()
    test_jsonl = (script_dir / args.test_jsonl).resolve()
    output_report = (script_dir / args.output_report).resolve()
    failure_log_jsonl = (
        (script_dir / args.failure_log_jsonl).resolve()
        if args.failure_log_jsonl
        else output_report.with_name(f"{output_report.stem}_failures.jsonl")
    )
    scale_config_path = (script_dir / args.absolute_scale_config).resolve()
    apply_absolute_scaling = not args.no_absolute_scaling

    if not base_model_dir.exists():
        raise FileNotFoundError(f"base model dir not found: {base_model_dir}")
    if not lora_model_dir.exists():
        raise FileNotFoundError(f"lora model dir not found: {lora_model_dir}")
    if not test_jsonl.exists():
        raise FileNotFoundError(f"test jsonl not found: {test_jsonl}")

    print(f"[INFO] base model: {base_model_dir}")
    print(f"[INFO] lora model: {lora_model_dir}")
    print(f"[INFO] test jsonl: {test_jsonl}")
    if apply_absolute_scaling:
        print(f"[INFO] absolute scaling config: {scale_config_path}")

    tokenizer = AutoTokenizer.from_pretrained(str(base_model_dir), local_files_only=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    device = "cuda" if torch.cuda.is_available() else "cpu"
    dtype = torch.bfloat16 if device == "cuda" else torch.float32
    model = AutoModelForCausalLM.from_pretrained(
        str(base_model_dir),
        local_files_only=True,
        torch_dtype=dtype,
    )
    model = PeftModel.from_pretrained(model, str(lora_model_dir))
    model.eval()
    model.to(device)
    print(f"[INFO] model ready on {device}")

    with open(test_jsonl, "r", encoding="utf-8") as f:
        samples = [json.loads(line) for line in f if line.strip()]
    if args.max_samples > 0:
        samples = samples[: args.max_samples]
    if not samples:
        raise ValueError("No samples to evaluate.")

    total = len(samples)
    parse_ok = 0
    aligned_ok = 0
    failure_printed = 0
    all_err_x = []
    all_err_y = []
    all_dist = []
    all_horizon = defaultdict(list)
    action_stats = defaultdict(
        lambda: {
            "total": 0,
            "parse_ok": 0,
            "aligned_ok": 0,
            "dist": [],
        }
    )
    failure_reason_counts = defaultdict(int)
    failure_records = []
    joint_axis_scales, scale_eps = (
        load_scale_config(scale_config_path) if apply_absolute_scaling else ({}, 1e-6)
    )

    for idx, row in enumerate(samples, 1):
        prompt = row.get("prompt", "")
        if args.append_target_prefix:
            prompt = f"{prompt}\n{MARKER}"
        gt_text = row.get("completion", "")
        action = row.get("action", "unknown")

        action_stats[action]["total"] += 1
        parse_label = "fail(format_collapse)"
        aligned_points = 0
        pred_text = ""
        pred_coords = {}

        try:
            inputs = tokenizer(prompt, return_tensors="pt").to(device)
            input_len = inputs["input_ids"].shape[1]

            gen_kwargs = {
                "max_new_tokens": args.max_new_tokens,
                "min_new_tokens": args.min_new_tokens,
                "repetition_penalty": args.repetition_penalty,
                "pad_token_id": tokenizer.eos_token_id,
                "eos_token_id": tokenizer.eos_token_id,
            }
            if args.do_sample:
                gen_kwargs["do_sample"] = True
                gen_kwargs["temperature"] = args.temperature
                gen_kwargs["top_p"] = args.top_p
            else:
                gen_kwargs["do_sample"] = False

            with torch.no_grad():
                outputs = model.generate(**inputs, **gen_kwargs)

            new_token_ids = outputs[0][input_len:]
            pred_text = tokenizer.decode(new_token_ids, skip_special_tokens=False)

            pred_coords = parse_coords(pred_text)
            gt_coords = parse_coords(gt_text)
            pred_coords = inverse_scale_coords(pred_coords, joint_axis_scales, scale_eps)
            gt_coords = inverse_scale_coords(gt_coords, joint_axis_scales, scale_eps)

            if pred_coords:
                parse_label = "ok"
                parse_ok += 1
                action_stats[action]["parse_ok"] += 1
            else:
                fail_reason = classify_format_failure(pred_text)
                failure_reason_counts[fail_reason] += 1
                failure_records.append(
                    {
                        "sample_index": idx,
                        "action": action,
                        "mode": "absolute",
                        "failure_type": "format_collapse",
                        "failure_reason": fail_reason,
                        "prompt_head": prompt[:200].replace("\n", " "),
                        "raw_output_head": pred_text[:800].replace("\n", "\\n"),
                    }
                )
                if failure_printed < args.debug_failures:
                    failure_printed += 1
                    print(f"\n[DEBUG parse_fail #{failure_printed}] action={action}")
                    print("[DEBUG prompt head]", safe_console_text(prompt[:200].replace("\n", " ")))
                    print("[DEBUG raw output head]", safe_console_text(pred_text[:800].replace("\n", "\\n")))

            m = evaluate_one(pred_coords, gt_coords)
            aligned_points = m["aligned_points"]
            if aligned_points > 0:
                aligned_ok += 1
                action_stats[action]["aligned_ok"] += 1
                all_err_x.extend(m["raw_err_x"])
                all_err_y.extend(m["raw_err_y"])
                all_dist.extend(m["raw_dist"])
                action_stats[action]["dist"].extend(m["raw_dist"])
                for h, values in m["raw_horizon_dist"].items():
                    all_horizon[h].extend(values)
        except Exception as e:
            parse_label = "error(runtime)"
            fail_reason = f"runtime_error:{type(e).__name__}"
            failure_reason_counts[fail_reason] += 1
            failure_records.append(
                {
                    "sample_index": idx,
                    "action": action,
                    "mode": "absolute",
                    "failure_type": "runtime_error",
                    "failure_reason": fail_reason,
                    "error_message": str(e),
                    "prompt_head": prompt[:200].replace("\n", " "),
                    "raw_output_head": pred_text[:800].replace("\n", "\\n"),
                }
            )
            print(f"[WARN] sample {idx}/{total} runtime error: {safe_console_text(str(e))}")

        print(f"[{idx}/{total}] action={action} parse={parse_label} aligned_points={aligned_points}")

    horizon_summary = {
        str(h): (sum(v) / len(v) if v else None)
        for h, v in sorted(all_horizon.items(), key=lambda x: x[0])
    }
    action_summary = {}
    for action, s in sorted(action_stats.items()):
        action_summary[action] = {
            "total": s["total"],
            "parse_success_rate": (s["parse_ok"] / s["total"]) if s["total"] else 0.0,
            "aligned_success_rate": (s["aligned_ok"] / s["total"]) if s["total"] else 0.0,
            "mean_dist": (sum(s["dist"]) / len(s["dist"])) if s["dist"] else None,
        }

    report = {
        "num_samples": total,
        "parse_success_rate": parse_ok / total,
        "aligned_success_rate": aligned_ok / total,
        "overall_mae_x": (sum(all_err_x) / len(all_err_x)) if all_err_x else None,
        "overall_mae_y": (sum(all_err_y) / len(all_err_y)) if all_err_y else None,
        "overall_mae_xy": ((sum(all_err_x) + sum(all_err_y)) / (len(all_err_x) + len(all_err_y)))
        if all_err_x
        else None,
        "overall_mean_dist": (sum(all_dist) / len(all_dist)) if all_dist else None,
        "horizon_mean_dist": horizon_summary,
        "action_summary": action_summary,
        "num_failures": len(failure_records),
        "failure_reason_counts": dict(sorted(failure_reason_counts.items(), key=lambda x: x[0])),
        "failure_samples": failure_records,
        "config": {
            "base_model_dir": str(base_model_dir),
            "lora_model_dir": str(lora_model_dir),
            "test_jsonl": str(test_jsonl),
            "failure_log_jsonl": str(failure_log_jsonl),
            "max_new_tokens": args.max_new_tokens,
            "do_sample": args.do_sample,
            "temperature": args.temperature,
            "top_p": args.top_p,
            "repetition_penalty": args.repetition_penalty,
            "device": device,
            "absolute_scale_config": str(scale_config_path),
            "absolute_scaling_enabled": apply_absolute_scaling,
        },
    }

    output_report.parent.mkdir(parents=True, exist_ok=True)
    with open(output_report, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    with open(failure_log_jsonl, "w", encoding="utf-8") as f:
        for row in failure_records:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print("\n[SUMMARY]")
    print(f"  samples: {report['num_samples']}")
    print(f"  parse success: {report['parse_success_rate']:.2%}")
    print(f"  aligned success: {report['aligned_success_rate']:.2%}")
    print(f"  MAE(x): {report['overall_mae_x']}")
    print(f"  MAE(y): {report['overall_mae_y']}")
    print(f"  MAE(xy): {report['overall_mae_xy']}")
    print(f"  Mean distance: {report['overall_mean_dist']}")
    print(f"  failures: {report['num_failures']}")
    print(f"  report saved: {output_report}")
    print(f"  failure log saved: {failure_log_jsonl}")


if __name__ == "__main__":
    main()
